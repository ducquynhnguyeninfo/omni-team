"""
Tool adapters — turn canonical roles/skills into each tool's native format.

Every generated file carries MARKER so install.py can recognise (and safely
overwrite or remove) its own output without touching files a human wrote.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Dict, Optional, Tuple

from .roles import Role, Skill, compose_instructions

MARKER = "generated by omni-team"
SOURCE_NOTE = "do not edit; regenerated by the omni-team installer (install.py --dir <project>)"

DEFAULT_CLAUDE_MODELS = {"deep": "opus", "standard": "sonnet", "fast": "haiku"}
DEFAULT_CODEX_EFFORT = {"deep": "high", "standard": "medium", "fast": "low"}

# `None` → omit the tools line so the agent inherits every tool, including
# whatever browser/device MCP the host has configured.
CLAUDE_TOOLS = {"read-only": "Read, Grep, Glob, Bash", "run": None}
CODEX_SANDBOX = {"read-only": "read-only", "run": "workspace-write"}

BLOCK_BEGIN = "<!-- omni-team:begin (managed by the omni-team installer; edits inside are overwritten) -->"
BLOCK_END = "<!-- omni-team:end -->"

POINTER_BODY = """## omni-team — AI review team

This repository vendors **omni-team** in `.omni-team/`: a stack-agnostic team of
delivery sub-agents (ba, architect, pm, tech-lead, code-reviewer, test-engineer,
data-reviewer, security-engineer, perf-engineer, qa-lead, smoke-tester,
release-manager).

- For any non-trivial change, follow **`.omni-team/AGENTS.md`**: define → design →
  plan → implement → Gate 0 checks → review gates → acceptance → stop at the human gate.
- Project facts and rules for the team: `.omni-team/project/profile.yaml` and
  `.omni-team/project/conventions.md`.
- Entry points: `omni-task` (full flow), `omni-plan`, `omni-review`, `omni-ship`, `omni-setup`,
  and per role `ba`, `architect`, `pm`, `release`.
- The team never commits, pushes or merges — shipping is a human decision."""


def yaml_scalar(value: str) -> str:
    """JSON strings are valid YAML double-quoted scalars and survive any punctuation."""
    return json.dumps(value, ensure_ascii=False)


def toml_basic(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def toml_multiline(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"""', '""\\"')
    return f'"""\n{escaped.rstrip()}\n"""'


def render_claude_agent(role: Role, protocol: str, models: Dict[str, str]) -> str:
    lines = [
        "---",
        f"name: {role.name}",
        f"description: {yaml_scalar(role.description)}",
    ]
    tools = CLAUDE_TOOLS[role.access]
    if tools:
        lines.append(f"tools: {tools}")
    lines += [f"model: {models[role.tier]}", "---", ""]
    header = "\n".join(lines)
    note = f"<!-- {MARKER} from .omni-team/team/{role.name}.md — {SOURCE_NOTE} -->\n\n"
    return header + note + compose_instructions(role, protocol)


def render_codex_agent(role: Role, protocol: str, efforts: Dict[str, str]) -> str:
    return (
        f"# {MARKER} from .omni-team/team/{role.name}.md — {SOURCE_NOTE}\n"
        f"name = {toml_basic(role.name)}\n"
        f"description = {toml_basic(role.description)}\n"
        f"model_reasoning_effort = {toml_basic(efforts[role.tier])}\n"
        f"sandbox_mode = {toml_basic(CODEX_SANDBOX[role.access])}\n"
        f"developer_instructions = {toml_multiline(compose_instructions(role, protocol))}\n"
    )


def render_skill(skill: Skill) -> str:
    """Same SKILL.md format works for Claude Code and Codex; add the marker after frontmatter."""
    lines = skill.text.splitlines()
    end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
    note = f"<!-- {MARKER} from .omni-team/skills/{skill.name}/SKILL.md — {SOURCE_NOTE} -->"
    return "\n".join(lines[: end + 1] + ["", note] + lines[end + 1:]).rstrip() + "\n"


def pointer_block() -> str:
    return f"{BLOCK_BEGIN}\n{POINTER_BODY}\n{BLOCK_END}\n"


# Any omni-team block, whatever wording its begin marker had in older versions.
_BLOCK_RE = re.compile(r"<!-- omni-team:begin\b.*?-->.*?" + re.escape(BLOCK_END), re.DOTALL)


def _without_blocks(text: str) -> Tuple[str, Optional[int]]:
    """Remove every omni-team block; return the rest and where the first block started."""
    first = _BLOCK_RE.search(text)
    return _BLOCK_RE.sub("", text), (first.start() if first else None)


def upsert_block(existing: Optional[str], block: str) -> str:
    """Replace the omni-team block in place (merging duplicates); append one if there is none.
    Everything outside the block is preserved byte for byte."""
    if not existing:
        return block
    rest, at = _without_blocks(existing)
    if at is None:
        return existing.rstrip("\n") + "\n\n" + block
    return rest[:at] + block.rstrip("\n") + rest[at:]


def remove_block(existing: str) -> str:
    rest, at = _without_blocks(existing)
    if at is None:
        return existing
    before, after = rest[:at].rstrip("\n"), rest[at:].lstrip("\n")
    return (before + "\n\n" + after).strip("\n") + "\n" if before or after else ""


MARKER_SCAN_BYTES = 256_000  # third-party skills can carry very long frontmatter before the marker


def is_managed(path: Path) -> bool:
    try:
        with path.open("r", encoding="utf-8") as fh:
            head = fh.read(MARKER_SCAN_BYTES)
    except (OSError, UnicodeDecodeError):
        return False
    return MARKER in head
